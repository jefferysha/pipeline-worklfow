#!/usr/bin/env node
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { validateDocumentPresentationAssets } from './document-presentation-schema.mjs'

const root = fileURLToPath(new URL('..', import.meta.url))
const load = async (path) => JSON.parse(await readFile(resolve(root, path), 'utf8'))

export async function generatedDocumentPresentationSource() {
  const registry = await load('templates/documents/registry.v1.yaml')
  const catalogFiles = await Promise.all(
    registry.locales.map(async (locale) => {
      const catalog = await load(`templates/documents/locales/${locale}.yaml`)
      return catalog
    }),
  )
  const errors = await validateDocumentPresentationAssets(root, registry, catalogFiles)
  if (errors.length > 0) {
    throw new Error(`Document Presentation assets 无效:\n${errors.join('\n')}`)
  }
  const catalogs = Object.fromEntries(catalogFiles.map((catalog) => [
    catalog.locale,
    catalog.templates,
  ]))
  const workflowStepLabels = Object.fromEntries(catalogFiles.map((catalog) => [
    catalog.locale,
    catalog.workflow_steps,
  ]))
  const templateIds = registry.templates.map((template) => template.id)
  const templates = Object.fromEntries(
    registry.templates.map(({ id, ...definition }) => [id, definition]),
  )
  return `/* This file is generated by tools/generate-document-presentation.mjs. Do not edit. */
import type { DocumentLocale } from '../types.js'

export const DOCUMENT_TEMPLATE_IDS = ${JSON.stringify(templateIds, null, 2)} as const
export type DocumentTemplateId = (typeof DOCUMENT_TEMPLATE_IDS)[number]

export const DOCUMENT_WORKFLOW_STEP_IDS = ${JSON.stringify(registry.workflow_steps, null, 2)} as const
export type DocumentWorkflowStepId = (typeof DOCUMENT_WORKFLOW_STEP_IDS)[number]

export interface DocumentTemplateDefinition {
  readonly kind: string
  readonly path: string
  readonly sections: readonly string[]
  readonly layout: readonly string[]
  readonly creation: 'missing-only'
}

export const DOCUMENT_PRESENTATION_REGISTRY = ${JSON.stringify({
    version: registry.version,
    templates,
  }, null, 2)} as const satisfies {
  readonly version: 'v1'
  readonly templates: Readonly<Record<DocumentTemplateId, DocumentTemplateDefinition>>
}

type LocaleTemplate = Readonly<Record<string, string>>
export type DocumentLocaleCatalog = Readonly<Record<DocumentTemplateId, LocaleTemplate>>

export const DOCUMENT_LOCALE_CATALOGS = ${JSON.stringify(catalogs, null, 2)} as const satisfies Readonly<
  Record<DocumentLocale, DocumentLocaleCatalog>
>

export const DOCUMENT_WORKFLOW_STEP_LABELS = ${JSON.stringify(workflowStepLabels, null, 2)} as const satisfies Readonly<
  Record<DocumentLocale, Readonly<Record<DocumentWorkflowStepId, string>>>
>
`
}

async function main() {
  const target = resolve(root, 'packages/kernel/src/documents/document-presentation.generated.ts')
  await writeFile(target, await generatedDocumentPresentationSource(), 'utf8')
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  await main()
}
